"""
OptiS Benchmark — Markdown Report Builder

A reusable builder class for assembling Markdown documents programmatically.

Key features:

* **Fluent API** — most methods return ``self`` for method chaining.
* **i18n support** — ``lang="zh_CN"`` switches built-in section labels.
* **Mermaid helpers** — ``mermaid_bar``, ``mermaid_pie`` for common chart types.
* **Typing-first** — full type hints.

Usage::

    builder = MdReportBuilder(lang="zh_CN")
    report = (
        builder
        .h1("Title")
        .p("Some text")
        .table(["Col1", "Col2"], [["A", "1"], ["B", "2"]])
        .mermaid_bar("My Chart", ["A", "B"], [3.0, 4.5])
        .build()
    )
"""

